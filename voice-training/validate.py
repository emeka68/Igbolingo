#!/usr/bin/env python3
"""
Validate recordings against prompts.csv and export an LJSpeech-style
metadata.csv ready for TTS training (Piper / VITS / Coqui) or for
publishing to Hugging Face.

Usage:
    python3 validate.py            # report coverage + problems
    python3 validate.py --export   # also write metadata.csv for completed clips

Expected layout:
    voice-training/
      prompts.csv          <- generated by generate_prompts.mjs
      recordings/          <- put your audio here, named <prompt_id>.wav
      metadata.csv         <- produced by --export
"""
import csv
import sys
import wave
from pathlib import Path

HERE = Path(__file__).parent
RECORDINGS = HERE / "recordings"
PROMPTS = HERE / "prompts.csv"

TARGET_RATES = (22050, 44100, 48000)


def load_prompts():
    with open(PROMPTS, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def check_wav(path: Path):
    """Return (ok, detail) for a wav file."""
    try:
        with wave.open(str(path), "rb") as w:
            rate, channels, frames = w.getframerate(), w.getnchannels(), w.getnframes()
            seconds = frames / float(rate) if rate else 0
        problems = []
        if rate not in TARGET_RATES:
            problems.append(f"sample rate {rate} (want one of {TARGET_RATES})")
        if channels != 1:
            problems.append(f"{channels} channels (want mono)")
        if seconds < 0.4:
            problems.append(f"only {seconds:.2f}s long (too short?)")
        return (not problems, "; ".join(problems) or f"{seconds:.1f}s ok")
    except Exception as e:  # non-wav (e.g. m4a) — flag for conversion
        return (False, f"not readable as WAV ({e}); convert with: ffmpeg -i in.m4a -ar 44100 -ac 1 out.wav")


def main():
    export = "--export" in sys.argv
    prompts = load_prompts()
    RECORDINGS.mkdir(exist_ok=True)

    recorded, missing, bad = [], [], []
    for p in prompts:
        path = RECORDINGS / f"{p['id']}.wav"
        if not path.exists():
            missing.append(p["id"])
            continue
        ok, detail = check_wav(path)
        (recorded if ok else bad).append((p, detail))

    # Orphan files that match no prompt
    known = {p["id"] for p in prompts}
    orphans = [f.name for f in RECORDINGS.glob("*.wav") if f.stem not in known]

    total = len(prompts)
    print(f"Prompts:   {total}")
    print(f"Recorded:  {len(recorded)} ok, {len(bad)} with problems")
    print(f"Missing:   {len(missing)}")
    if bad:
        print("\nProblem files:")
        for p, detail in bad:
            print(f"  {p['id']}.wav — {detail}")
    if orphans:
        print(f"\nOrphan files (no matching prompt): {', '.join(orphans)}")
    if missing and len(missing) <= 25:
        print(f"\nStill to record: {', '.join(missing)}")

    if export:
        out = HERE / "metadata.csv"
        with open(out, "w", encoding="utf-8") as f:
            # LJSpeech format: id|transcript (pipe-delimited, no header)
            for p, _ in recorded:
                text = p["text"]
                if p["category"] == "unscripted" and text.startswith("("):
                    continue  # skip until transcribed
                f.write(f"{p['id']}|{text}\n")
        print(f"\nWrote {out.name} with {len(recorded)} aligned clips (LJSpeech format).")

    pct = 100 * len(recorded) / total if total else 0
    print(f"\nCoverage: {pct:.0f}%")


if __name__ == "__main__":
    main()
